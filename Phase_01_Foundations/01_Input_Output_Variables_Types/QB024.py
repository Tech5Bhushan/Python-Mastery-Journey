# Q24. Write a Python program to get the Identity, Type, and Value of an object

a = 'Bhushan'
print("Identity: ", id(a))
print("Type: ", type(a))
print("Value: ",a)


# In Python:
#
# Identity → Memory address of the object (id()) --> The Identity value will be different on every system and every execution.
# Type → Data type of the object (type())
# Value → Actual value stored in the object