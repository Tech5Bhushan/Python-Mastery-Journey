# Q15. Write a Python program to parse a string to float or integer.


# Solution 1: Convert String to Integer
num = "100"

result = int(num)

print(result)
print(type(result))

# Solution 2: Convert String to Float
num = "100.25"

result = float(num)

print(result)
print(type(result))

# Solution 3: Convert to Both Integer and Float
num = "25"

print("Integer:", int(num))
print("Float:", float(num))


